/*
# Create PulseMetrics schema and seed synthetic order logs

Plain-English summary: adds the tables that store uploaded or sample transaction logs, and fills in a sample dataset of 2,000 synthetic orders so the dashboard has data on first load.

## 1. New tables
- `datasets`: one row per imported transaction log (id, name, source, created_at). `source` is either 'sample' (the built-in synthetic data) or 'upload' (a CSV the user imported).
- `order_logs`: one row per order (id, dataset_id, customer_id, join_date, order_date, order_value_kes, status).

## 2. Seed data
- Inserts one sample dataset with a fixed id and 2,000 synthetic orders from roughly 450 customers spanning January 2024 to October 2026.
- Re-running this migration does not duplicate the sample data.

## 3. Security
- Row level security is enabled on both tables.
- This app has no sign-in, so the anon and authenticated roles can read and insert. No update or delete access is granted.

## 4. Notes
- Indexes are added on dataset_id and (dataset_id, customer_id) for fast per-dataset queries.
*/

CREATE TABLE IF NOT EXISTS datasets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  source text NOT NULL DEFAULT 'upload' CHECK (source IN ('sample', 'upload')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS order_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id uuid NOT NULL REFERENCES datasets(id) ON DELETE CASCADE,
  customer_id text NOT NULL,
  join_date date NOT NULL,
  order_date date NOT NULL,
  order_value_kes numeric(12, 2) NOT NULL,
  status text NOT NULL
);

CREATE INDEX IF NOT EXISTS order_logs_dataset_idx ON order_logs (dataset_id);
CREATE INDEX IF NOT EXISTS order_logs_dataset_customer_idx ON order_logs (dataset_id, customer_id);

ALTER TABLE datasets ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_logs ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT ON datasets TO anon, authenticated;
GRANT SELECT, INSERT ON order_logs TO anon, authenticated;

DROP POLICY IF EXISTS "anon_select_datasets" ON datasets;
CREATE POLICY "anon_select_datasets" ON datasets FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_datasets" ON datasets;
CREATE POLICY "anon_insert_datasets" ON datasets FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_select_order_logs" ON order_logs;
CREATE POLICY "anon_select_order_logs" ON order_logs FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_order_logs" ON order_logs;
CREATE POLICY "anon_insert_order_logs" ON order_logs FOR INSERT
  TO anon, authenticated WITH CHECK (true);

INSERT INTO datasets (id, name, source)
VALUES ('a0000000-0000-4000-8000-000000000001', 'Sample transactions (synthetic)', 'sample')
ON CONFLICT (id) DO NOTHING;

WITH customers AS MATERIALIZED (
  SELECT
    g AS n,
    'CUS-' || lpad(g::text, 4, '0') AS cid,
    floor(random() * 31)::int AS join_idx,
    1 + floor(-ln(1 - random()) * 6)::int AS life
  FROM generate_series(1, 450) g
),
spans AS MATERIALIZED (
  SELECT
    n,
    cid,
    join_idx,
    LEAST(join_idx + life, 34) AS end_idx,
    ((DATE '2024-01-01' + make_interval(months => join_idx))::date + floor(random() * 27)::int) AS join_d
  FROM customers
),
candidates AS (
  SELECT
    s.n,
    s.cid,
    s.join_d,
    ((DATE '2024-01-01' + make_interval(months => m))::date + floor(random() * 27)::int) AS raw_od
  FROM spans s
  CROSS JOIN generate_series(0, 33) AS m
  WHERE m >= s.join_idx AND m < s.end_idx AND random() < 0.85
),
picked AS (
  SELECT n, cid, join_d, GREATEST(raw_od, join_d) AS od
  FROM candidates
  ORDER BY random()
  LIMIT 2000
)
INSERT INTO order_logs (dataset_id, customer_id, join_date, order_date, order_value_kes, status)
SELECT
  'a0000000-0000-4000-8000-000000000001'::uuid,
  p.cid,
  p.join_d,
  p.od,
  round(((400 + random() * 1800) * (1 + (p.n % 3) * 0.35)) / 10) * 10,
  CASE WHEN random() < 0.93 THEN 'completed' WHEN random() < 0.6 THEN 'refunded' ELSE 'failed' END
FROM picked p
WHERE NOT EXISTS (
  SELECT 1 FROM order_logs WHERE dataset_id = 'a0000000-0000-4000-8000-000000000001'::uuid
);
